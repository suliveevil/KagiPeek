import Foundation

/// Renders a shortcut sheet as Markdown, for the search palette's export.
enum MarkdownExporter {
    static func render(
        appName: String,
        items: [BindingItem],
        style: KeyFormatter.Style,
        language: AppLanguage,
        generatedAt: Date = Date(),
        timeZone: TimeZone = .current
    ) -> String {
        let formatter = ISO8601DateFormatter()
        formatter.timeZone = timeZone
        let stamp = formatter.string(from: generatedAt)

        var lines: [String] = []
        lines.append("# KagiPeek — \(appName)")
        lines.append("")
        lines.append("_Generated \(stamp) · \(items.count) shortcuts_")
        lines.append("")

        var order: [String] = []
        var buckets: [String: [BindingItem]] = [:]
        for item in items {
            let group = item.displayGroup.isEmpty
                ? L10n.string(.groupSystem, language: language)
                : item.displayGroup
            if buckets[group] == nil {
                order.append(group)
                buckets[group] = []
            }
            buckets[group]?.append(item)
        }

        for group in order {
            guard let rows = buckets[group], !rows.isEmpty else { continue }
            lines.append("## \(group)")
            lines.append("")
            lines.append("| Shortcut | Action |")
            lines.append("| --- | --- |")
            for item in rows {
                // The dash keeps the table readable and says the same thing the panel says:
                // this command is triggered by pressing the menu item, not by typing.
                let keys = (item.chord.isEmpty
                    ? KeyFormatter.noShortcutPlaceholder
                    : KeyFormatter.render(item.chord, style: style))
                    .replacingOccurrences(of: "|", with: "\\|")
                var title = item.title.replacingOccurrences(of: "|", with: "\\|")
                if !item.isEnabled {
                    title += " _(unavailable)_"
                }
                lines.append("| `\(keys)` | \(title) |")
            }
            lines.append("")
        }

        lines.append("---")
        lines.append("")
        lines.append("Generated by [KagiPeek](https://github.com/suliveevil/KagiPeek).")
        lines.append("")
        return lines.joined(separator: "\n")
    }
}
